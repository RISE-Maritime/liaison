#!/usr/bin/env python3
"""
Memory Profile Analysis Script for Liaison FMI

This script analyzes memory profiling results generated by memory_profile.sh,
parses Massif output, generates comparison charts and tables, and highlights
significant differences.

Usage:
    python3 analyze_memory.py <results_dir> [--compare <other_results_dir>]

Options:
    results_dir           Directory containing profiling results
    --compare DIR         Compare with another results directory
    --export-csv          Export results to CSV files
    --plot                Generate memory usage plots (requires matplotlib)
    --verbose             Show detailed output

Requirements:
    - Python 3.6+
    - matplotlib (optional, for plotting)
    - pandas (optional, for advanced analysis)
"""

import argparse
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Dict, Tuple
import json


@dataclass
class MemorySnapshot:
    """Represents a memory snapshot from Massif output"""
    snapshot_number: int
    time: float  # milliseconds
    heap_bytes: int
    heap_extra_bytes: int
    stacks_bytes: int
    total_bytes: int


@dataclass
class MemoryProfile:
    """Complete memory profile from a Massif run"""
    command: str
    time_unit: str
    snapshots: List[MemorySnapshot]
    peak_snapshot: Optional[MemorySnapshot] = None

    @property
    def peak_memory_mb(self) -> float:
        """Peak memory in MB"""
        if self.peak_snapshot:
            return self.peak_snapshot.total_bytes / (1024 * 1024)
        return 0.0

    @property
    def final_memory_mb(self) -> float:
        """Final memory usage in MB"""
        if self.snapshots:
            return self.snapshots[-1].total_bytes / (1024 * 1024)
        return 0.0


class MassifParser:
    """Parser for Valgrind Massif output files"""

    @staticmethod
    def parse_massif_file(filepath: Path) -> Optional[MemoryProfile]:
        """Parse a Massif output file"""
        if not filepath.exists():
            print(f"Warning: File not found: {filepath}")
            return None

        try:
            with open(filepath, 'r') as f:
                content = f.read()
        except Exception as e:
            print(f"Error reading {filepath}: {e}")
            return None

        # Parse header
        command = ""
        time_unit = ""

        for line in content.split('\n'):
            if line.startswith('cmd:'):
                command = line[4:].strip()
            elif line.startswith('time_unit:'):
                time_unit = line[10:].strip()

        # Parse snapshots
        snapshots = []
        snapshot_blocks = re.findall(
            r'snapshot=(\d+)\n' +
            r'#-+\n' +
            r'time=([0-9.]+)\n' +
            r'mem_heap_B=(\d+)\n' +
            r'mem_heap_extra_B=(\d+)\n' +
            r'mem_stacks_B=(\d+)',
            content
        )

        for block in snapshot_blocks:
            snapshot = MemorySnapshot(
                snapshot_number=int(block[0]),
                time=float(block[1]),
                heap_bytes=int(block[2]),
                heap_extra_bytes=int(block[3]),
                stacks_bytes=int(block[4]),
                total_bytes=int(block[2]) + int(block[3]) + int(block[4])
            )
            snapshots.append(snapshot)

        profile = MemoryProfile(
            command=command,
            time_unit=time_unit,
            snapshots=snapshots
        )

        # Find peak
        if snapshots:
            profile.peak_snapshot = max(snapshots, key=lambda s: s.total_bytes)

        return profile


class MemoryAnalyzer:
    """Analyzes memory profiling results"""

    def __init__(self, results_dir: Path, verbose: bool = False):
        self.results_dir = results_dir
        self.verbose = verbose
        self.server_profile: Optional[MemoryProfile] = None
        self.client_profile: Optional[MemoryProfile] = None

    def load_profiles(self):
        """Load memory profiles from results directory"""
        # Load server profile
        server_massif = self.results_dir / "server" / "massif.out"
        if server_massif.exists():
            self.server_profile = MassifParser.parse_massif_file(server_massif)
            if self.verbose and self.server_profile:
                print(f"Loaded server profile: {len(self.server_profile.snapshots)} snapshots")

        # Load client profile
        client_massif = self.results_dir / "client" / "massif.out"
        if client_massif.exists():
            self.client_profile = MassifParser.parse_massif_file(client_massif)
            if self.verbose and self.client_profile:
                print(f"Loaded client profile: {len(self.client_profile.snapshots)} snapshots")

    def print_summary(self):
        """Print summary of memory usage"""
        print("\n" + "=" * 70)
        print(" " * 20 + "MEMORY PROFILE SUMMARY")
        print("=" * 70)

        if self.server_profile:
            print("\n--- SERVER MEMORY ---")
            print(f"Peak memory:  {self.server_profile.peak_memory_mb:>10.2f} MB")
            print(f"Final memory: {self.server_profile.final_memory_mb:>10.2f} MB")
            print(f"Snapshots:    {len(self.server_profile.snapshots):>10}")

            if self.server_profile.peak_snapshot:
                peak = self.server_profile.peak_snapshot
                print(f"Peak at:      {peak.time:>10.2f} {self.server_profile.time_unit}")

        if self.client_profile:
            print("\n--- CLIENT MEMORY ---")
            print(f"Peak memory:  {self.client_profile.peak_memory_mb:>10.2f} MB")
            print(f"Final memory: {self.client_profile.final_memory_mb:>10.2f} MB")
            print(f"Snapshots:    {len(self.client_profile.snapshots):>10}")

            if self.client_profile.peak_snapshot:
                peak = self.client_profile.peak_snapshot
                print(f"Peak at:      {peak.time:>10.2f} {self.client_profile.time_unit}")

        print("\n" + "=" * 70 + "\n")

    def generate_detailed_report(self, output_file: Path):
        """Generate detailed markdown report"""
        with open(output_file, 'w') as f:
            f.write("# Detailed Memory Profile Analysis\n\n")
            f.write(f"**Results Directory:** `{self.results_dir}`\n\n")

            # Server analysis
            if self.server_profile:
                f.write("## Server Memory Profile\n\n")
                f.write(f"- **Command:** `{self.server_profile.command}`\n")
                f.write(f"- **Peak Memory:** {self.server_profile.peak_memory_mb:.2f} MB\n")
                f.write(f"- **Final Memory:** {self.server_profile.final_memory_mb:.2f} MB\n")
                f.write(f"- **Total Snapshots:** {len(self.server_profile.snapshots)}\n\n")

                if self.server_profile.snapshots:
                    f.write("### Memory Timeline (Server)\n\n")
                    f.write("| Time (ms) | Heap (MB) | Total (MB) |\n")
                    f.write("|-----------|-----------|------------|\n")

                    # Sample every N snapshots for readability
                    sample_rate = max(1, len(self.server_profile.snapshots) // 20)
                    for i, snap in enumerate(self.server_profile.snapshots):
                        if i % sample_rate == 0 or snap == self.server_profile.peak_snapshot:
                            heap_mb = snap.heap_bytes / (1024 * 1024)
                            total_mb = snap.total_bytes / (1024 * 1024)
                            marker = " (PEAK)" if snap == self.server_profile.peak_snapshot else ""
                            f.write(f"| {snap.time:>9.1f} | {heap_mb:>9.2f} | {total_mb:>10.2f}{marker} |\n")

                    f.write("\n")

            # Client analysis
            if self.client_profile:
                f.write("## Client Memory Profile\n\n")
                f.write(f"- **Command:** `{self.client_profile.command}`\n")
                f.write(f"- **Peak Memory:** {self.client_profile.peak_memory_mb:.2f} MB\n")
                f.write(f"- **Final Memory:** {self.client_profile.final_memory_mb:.2f} MB\n")
                f.write(f"- **Total Snapshots:** {len(self.client_profile.snapshots)}\n\n")

                if self.client_profile.snapshots:
                    f.write("### Memory Timeline (Client)\n\n")
                    f.write("| Time (ms) | Heap (MB) | Total (MB) |\n")
                    f.write("|-----------|-----------|------------|\n")

                    sample_rate = max(1, len(self.client_profile.snapshots) // 20)
                    for i, snap in enumerate(self.client_profile.snapshots):
                        if i % sample_rate == 0 or snap == self.client_profile.peak_snapshot:
                            heap_mb = snap.heap_bytes / (1024 * 1024)
                            total_mb = snap.total_bytes / (1024 * 1024)
                            marker = " (PEAK)" if snap == self.client_profile.peak_snapshot else ""
                            f.write(f"| {snap.time:>9.1f} | {heap_mb:>9.2f} | {total_mb:>10.2f}{marker} |\n")

                    f.write("\n")

        print(f"Detailed report saved to: {output_file}")

    def export_to_csv(self, output_dir: Path):
        """Export profiles to CSV files"""
        output_dir.mkdir(parents=True, exist_ok=True)

        if self.server_profile and self.server_profile.snapshots:
            csv_file = output_dir / "server_memory.csv"
            with open(csv_file, 'w') as f:
                f.write("snapshot,time_ms,heap_bytes,heap_extra_bytes,stacks_bytes,total_bytes\n")
                for snap in self.server_profile.snapshots:
                    f.write(f"{snap.snapshot_number},{snap.time},{snap.heap_bytes},"
                           f"{snap.heap_extra_bytes},{snap.stacks_bytes},{snap.total_bytes}\n")
            print(f"Server CSV exported to: {csv_file}")

        if self.client_profile and self.client_profile.snapshots:
            csv_file = output_dir / "client_memory.csv"
            with open(csv_file, 'w') as f:
                f.write("snapshot,time_ms,heap_bytes,heap_extra_bytes,stacks_bytes,total_bytes\n")
                for snap in self.client_profile.snapshots:
                    f.write(f"{snap.snapshot_number},{snap.time},{snap.heap_bytes},"
                           f"{snap.heap_extra_bytes},{snap.stacks_bytes},{snap.total_bytes}\n")
            print(f"Client CSV exported to: {csv_file}")

    def plot_memory_usage(self, output_file: Path):
        """Generate memory usage plots"""
        try:
            import matplotlib.pyplot as plt
        except ImportError:
            print("Warning: matplotlib not available. Install with: pip install matplotlib")
            return

        fig, axes = plt.subplots(2, 1, figsize=(12, 10))

        # Plot server
        if self.server_profile and self.server_profile.snapshots:
            ax = axes[0]
            times = [s.time for s in self.server_profile.snapshots]
            memory = [s.total_bytes / (1024 * 1024) for s in self.server_profile.snapshots]

            ax.plot(times, memory, 'b-', linewidth=2, label='Total Memory')
            ax.axhline(y=self.server_profile.peak_memory_mb, color='r',
                      linestyle='--', label=f'Peak: {self.server_profile.peak_memory_mb:.2f} MB')

            ax.set_xlabel(f'Time ({self.server_profile.time_unit})')
            ax.set_ylabel('Memory (MB)')
            ax.set_title('Server Memory Usage Over Time')
            ax.legend()
            ax.grid(True, alpha=0.3)

        # Plot client
        if self.client_profile and self.client_profile.snapshots:
            ax = axes[1]
            times = [s.time for s in self.client_profile.snapshots]
            memory = [s.total_bytes / (1024 * 1024) for s in self.client_profile.snapshots]

            ax.plot(times, memory, 'g-', linewidth=2, label='Total Memory')
            ax.axhline(y=self.client_profile.peak_memory_mb, color='r',
                      linestyle='--', label=f'Peak: {self.client_profile.peak_memory_mb:.2f} MB')

            ax.set_xlabel(f'Time ({self.client_profile.time_unit})')
            ax.set_ylabel('Memory (MB)')
            ax.set_title('Client Memory Usage Over Time')
            ax.legend()
            ax.grid(True, alpha=0.3)

        plt.tight_layout()
        plt.savefig(output_file, dpi=150, bbox_inches='tight')
        print(f"Plot saved to: {output_file}")
        plt.close()


class MemoryComparator:
    """Compares two memory profile results"""

    def __init__(self, baseline: MemoryAnalyzer, current: MemoryAnalyzer):
        self.baseline = baseline
        self.current = current

    def compare(self) -> Dict[str, any]:
        """Compare two profiles and return differences"""
        comparison = {
            'server': {},
            'client': {},
        }

        # Compare server
        if self.baseline.server_profile and self.current.server_profile:
            baseline_peak = self.baseline.server_profile.peak_memory_mb
            current_peak = self.current.server_profile.peak_memory_mb
            diff_mb = current_peak - baseline_peak
            diff_pct = (diff_mb / baseline_peak * 100) if baseline_peak > 0 else 0

            comparison['server'] = {
                'baseline_peak_mb': baseline_peak,
                'current_peak_mb': current_peak,
                'difference_mb': diff_mb,
                'difference_pct': diff_pct,
            }

        # Compare client
        if self.baseline.client_profile and self.current.client_profile:
            baseline_peak = self.baseline.client_profile.peak_memory_mb
            current_peak = self.current.client_profile.peak_memory_mb
            diff_mb = current_peak - baseline_peak
            diff_pct = (diff_mb / baseline_peak * 100) if baseline_peak > 0 else 0

            comparison['client'] = {
                'baseline_peak_mb': baseline_peak,
                'current_peak_mb': current_peak,
                'difference_mb': diff_mb,
                'difference_pct': diff_pct,
            }

        return comparison

    def print_comparison(self):
        """Print comparison results"""
        comp = self.compare()

        print("\n" + "=" * 70)
        print(" " * 20 + "MEMORY PROFILE COMPARISON")
        print("=" * 70)

        if comp['server']:
            s = comp['server']
            print("\n--- SERVER ---")
            print(f"Baseline peak: {s['baseline_peak_mb']:>10.2f} MB")
            print(f"Current peak:  {s['current_peak_mb']:>10.2f} MB")
            print(f"Difference:    {s['difference_mb']:>+10.2f} MB ({s['difference_pct']:>+6.1f}%)")

            if abs(s['difference_pct']) > 10:
                indicator = "⚠️  SIGNIFICANT CHANGE" if abs(s['difference_pct']) > 20 else "ℹ️  Notable change"
                print(f"\n{indicator}")

        if comp['client']:
            c = comp['client']
            print("\n--- CLIENT ---")
            print(f"Baseline peak: {c['baseline_peak_mb']:>10.2f} MB")
            print(f"Current peak:  {c['current_peak_mb']:>10.2f} MB")
            print(f"Difference:    {c['difference_mb']:>+10.2f} MB ({c['difference_pct']:>+6.1f}%)")

            if abs(c['difference_pct']) > 10:
                indicator = "⚠️  SIGNIFICANT CHANGE" if abs(c['difference_pct']) > 20 else "ℹ️  Notable change"
                print(f"\n{indicator}")

        print("\n" + "=" * 70 + "\n")

    def generate_comparison_report(self, output_file: Path):
        """Generate comparison report"""
        comp = self.compare()

        with open(output_file, 'w') as f:
            f.write("# Memory Profile Comparison Report\n\n")
            f.write(f"**Baseline:** `{self.baseline.results_dir}`\n")
            f.write(f"**Current:**  `{self.current.results_dir}`\n\n")

            if comp['server']:
                s = comp['server']
                f.write("## Server Comparison\n\n")
                f.write(f"| Metric | Baseline | Current | Difference |\n")
                f.write(f"|--------|----------|---------|------------|\n")
                f.write(f"| Peak Memory | {s['baseline_peak_mb']:.2f} MB | "
                       f"{s['current_peak_mb']:.2f} MB | "
                       f"{s['difference_mb']:+.2f} MB ({s['difference_pct']:+.1f}%) |\n\n")

                if abs(s['difference_pct']) > 20:
                    f.write("⚠️  **Warning:** Significant memory change detected!\n\n")

            if comp['client']:
                c = comp['client']
                f.write("## Client Comparison\n\n")
                f.write(f"| Metric | Baseline | Current | Difference |\n")
                f.write(f"|--------|----------|---------|------------|\n")
                f.write(f"| Peak Memory | {c['baseline_peak_mb']:.2f} MB | "
                       f"{c['current_peak_mb']:.2f} MB | "
                       f"{c['difference_mb']:+.2f} MB ({c['difference_pct']:+.1f}%) |\n\n")

                if abs(c['difference_pct']) > 20:
                    f.write("⚠️  **Warning:** Significant memory change detected!\n\n")

        print(f"Comparison report saved to: {output_file}")


def main():
    parser = argparse.ArgumentParser(
        description='Analyze memory profiling results for Liaison FMI',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__
    )
    parser.add_argument('results_dir', type=Path,
                       help='Directory containing profiling results')
    parser.add_argument('--compare', type=Path, metavar='DIR',
                       help='Compare with another results directory')
    parser.add_argument('--export-csv', action='store_true',
                       help='Export results to CSV files')
    parser.add_argument('--plot', action='store_true',
                       help='Generate memory usage plots')
    parser.add_argument('--verbose', action='store_true',
                       help='Show detailed output')

    args = parser.parse_args()

    if not args.results_dir.exists():
        print(f"Error: Results directory not found: {args.results_dir}")
        sys.exit(1)

    # Analyze current results
    analyzer = MemoryAnalyzer(args.results_dir, verbose=args.verbose)
    analyzer.load_profiles()
    analyzer.print_summary()

    # Generate detailed report
    report_file = args.results_dir / "ANALYSIS.md"
    analyzer.generate_detailed_report(report_file)

    # Export to CSV if requested
    if args.export_csv:
        csv_dir = args.results_dir / "csv"
        analyzer.export_to_csv(csv_dir)

    # Generate plots if requested
    if args.plot:
        plot_file = args.results_dir / "memory_usage.png"
        analyzer.plot_memory_usage(plot_file)

    # Comparison if requested
    if args.compare:
        if not args.compare.exists():
            print(f"Error: Comparison directory not found: {args.compare}")
            sys.exit(1)

        baseline = MemoryAnalyzer(args.compare, verbose=args.verbose)
        baseline.load_profiles()

        comparator = MemoryComparator(baseline, analyzer)
        comparator.print_comparison()

        comparison_file = args.results_dir / "COMPARISON.md"
        comparator.generate_comparison_report(comparison_file)


if __name__ == '__main__':
    main()
